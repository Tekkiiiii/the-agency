#!/usr/bin/env python3
"""skill-registry.py - generate skills/INDEX.md from the skills on disk, and lint the skills.

  python3 scripts/skill-registry.py                  write skills/INDEX.md (no-op when it is already current)
  python3 scripts/skill-registry.py --check          exit 1 if skills/INDEX.md is stale (CI; writes nothing)
  python3 scripts/skill-registry.py --lint           ratcheting lint; exit 1 only for violations NOT in the baseline
  python3 scripts/skill-registry.py --lint --changed-only PATH [PATH ...]
                                                     lint only the skill dirs containing those paths
  python3 scripts/skill-registry.py --lint --update-baseline [--changed-only PATH ...]
                                                     accept today's violations (or drop fixed ones) in the baseline

--root DIR picks the agency root (default: the directory above scripts/, so it works in a checkout and in an
install alike). --baseline FILE picks another baseline. Stdlib only; Python 3.9+; Linux, macOS, Windows.

INDEX.md is GENERATED. The skill set is the set of skills/<name>/SKILL.md on disk (directories starting with
"_" or "." are not skills), so the file cannot drift from the tree. Nothing in it is hand-kept except the
two text files it is glued from:
    scripts/skill-registry/header.md   everything above the tables (title, how discovery works)
    scripts/skill-registry/footer.md   everything below them (usage, creating a skill)
In between: one table per router domain (domains and membership come from scripts/skill-route/overlay.json, read
only; domain order = overlay order, rows sorted by skill name), then a table of skills the router hides
(overlay `exclude`) and a table of skills with no overlay entry. A skill's description is its SKILL.md frontmatter
`description` (whitespace collapsed, cut at 140 chars on a word boundary); with no frontmatter or no description it
is the first paragraph of the body, so a skill without frontmatter is still listed and still invokable. The output
carries no date and no count, so regenerating twice gives a byte-identical file.

There is deliberately no INDEX.catalog.json: nothing in this repo reads one (the router takes triggers from the
overlay and descriptions from SKILL.md), and a second generated file is a second thing to drift.

--lint rules (key = "<skill>:<rule>"; scripts/skill-registry/lint-baseline.json holds the accepted set):
  body-tokens>5000     SKILL.md body longer than 5000 tokens (len // 4)
  body-lines>500       SKILL.md body longer than 500 lines
  description>400      frontmatter description + when_to_use longer than 400 chars (the menu budget)
  refs-two-deep        a references/ file that links to another references/ file (one level deep only)
  hardcoded-self-path  SKILL.md names its own dir under a machine path (a home-dir or $HOME path to
                       skills/<dir>/); use {agency-root}/skills/<dir>/ or ${CLAUDE_SKILL_DIR}
  non-spec-key:<key>   top-level frontmatter key outside the Agent Skills spec set; custom keys go under `metadata:`
                       with string values
Only NEW keys fail. Baseline entries that no longer fire print "LINT FIXED"; --update-baseline drops them. The baseline
is meant to shrink: never add to it by hand to get a commit through, fix the skill.
"""
import argparse
import json
import os
import re
import sys

SPEC = {"name", "description", "license", "allowed-tools", "metadata", "compatibility", "when_to_use",
        "argument-hint", "disable-model-invocation", "user-invocable", "model", "effort", "context", "agent",
        "paths", "hooks", "shell", "disallowed-tools", "version"}
REF_TEXT = (".md", ".mdx", ".txt", ".rst")
REF_MENTION = re.compile(r"references/[A-Za-z0-9_./-]+")
MD_LINK = re.compile(r"\]\(([^)\s#]+)(?:#[^)]*)?\)")
KEY_RE = re.compile(r"^([A-Za-z0-9_-]+):")

GENERATED_NOTE = ("<!-- GENERATED by `python3 scripts/skill-registry.py`; do not edit below this line. "
                  "Hand-kept parts: scripts/skill-registry/header.md and footer.md. -->")


# ---------------------------------------------------------------------------------------------- paths / io
def default_root():
    return os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def read_text(path):
    """utf-8 text with universal newlines (a CRLF checkout reads like an LF one); None when unreadable."""
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            return fh.read()
    except OSError:
        return None


def read_json(path, default):
    try:
        with open(path, encoding="utf-8") as fh:
            return json.load(fh)
    except (OSError, ValueError):
        return default


def write_text(path, text):
    """Atomic write, LF line endings on every platform; temp file removed on error."""
    tmp = "%s.tmp.%d" % (path, os.getpid())
    try:
        with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


# ---------------------------------------------------------------------------------------------- frontmatter
def split_frontmatter(text):
    """-> (frontmatter lines, body text). No frontmatter, or an opening --- that never closes: ([], whole text)."""
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        return [], text
    end = next((i for i in range(1, len(lines)) if lines[i].strip() == "---"), None)
    if end is None:
        return [], text
    return lines[1:end], "\n".join(lines[end + 1:])


def _dq_end(s):
    i = 1
    while i < len(s):
        if s[i] == "\\":
            i += 2
            continue
        if s[i] == '"':
            return i
        i += 1
    return -1


def _sq_end(s):
    i = 1
    while i < len(s):
        if s[i] == "'":
            if s[i + 1:i + 2] == "'":
                i += 2
                continue
            return i
        i += 1
    return -1


def unquote(val):
    """YAML scalar text -> str: "dq" (JSON escapes), 'sq' ('' escape), plain."""
    val = val.strip()
    if val[:1] == '"':
        end = _dq_end(val)
        body = val if end < 0 else val[:end + 1]
        try:
            return json.loads(body)
        except ValueError:
            return body.strip('"').replace('\\"', '"').replace("\\\\", "\\")
    if val[:1] == "'":
        end = _sq_end(val)
        return (val[1:] if end < 0 else val[1:end]).replace("''", "'")
    return val


def fm_value(fm, key):
    """Frontmatter top-level `key` as a single string (whitespace collapsed); '' when absent.
    Handles plain, "quoted" / 'quoted' (also when wrapped over lines) and >, | block scalars."""
    pat = re.compile(r"^%s:[ \t]*(.*)$" % re.escape(key))
    i, out = 0, ""
    while i < len(fm):
        m = pat.match(fm[i])
        i += 1
        if not m:
            continue
        val, parts = m.group(1).rstrip(), []
        if val[:1] in ("|", ">"):
            while i < len(fm) and (fm[i].startswith((" ", "\t")) or not fm[i].strip()):
                parts.append(fm[i].strip())
                i += 1
            out = " ".join(p for p in parts if p)
        elif val[:1] in ('"', "'"):
            end = _dq_end if val[0] == '"' else _sq_end
            buf = val
            while end(buf) < 0 and i < len(fm):
                buf += " " + fm[i].strip()
                i += 1
            out = unquote(buf)
        else:
            parts = [val]
            while i < len(fm) and fm[i].startswith((" ", "\t")):
                parts.append(fm[i].strip())
                i += 1
            out = " ".join(p for p in parts if p)
        break
    return re.sub(r"\s+", " ", out).strip()


def fm_keys(fm):
    """Top-level frontmatter keys in file order."""
    keys = []
    for ln in fm:
        m = KEY_RE.match(ln)
        if m and not ln.startswith((" ", "\t")):
            keys.append(m.group(1))
    return keys


def first_paragraph(body):
    """First prose paragraph of a markdown body (skips headings, fences, comments, rules); '' when there is none."""
    para, fenced = [], False
    for ln in body.split("\n"):
        s = ln.strip()
        if s.startswith("```"):
            fenced = not fenced
            continue
        if fenced:
            continue
        if not s:
            if para:
                break
            continue
        if s.startswith(("#", "<!--", "---", "===", "|")) and not para:
            continue
        para.append(s)
    return re.sub(r"\s+", " ", " ".join(para)).strip()


# ---------------------------------------------------------------------------------------------- skill set
def skills_dir(root):
    return os.path.join(root, "skills")


def list_skills(root):
    """[(name, dir path)] sorted by name: depth-1 dirs holding a SKILL.md; "_x" and ".x" dirs are not skills."""
    base = skills_dir(root)
    found = []
    for d in sorted(os.listdir(base)) if os.path.isdir(base) else []:
        p = os.path.join(base, d)
        if d.startswith(("_", ".")) or not os.path.isdir(p) or not os.path.isfile(os.path.join(p, "SKILL.md")):
            continue
        found.append((d, p))
    return found


def load_skill(p):
    text = read_text(os.path.join(p, "SKILL.md")) or ""
    fm, body = split_frontmatter(text)
    return text, fm, body


# ---------------------------------------------------------------------------------------------- INDEX.md
def short(desc, n=140):
    d = re.sub(r"\s+", " ", desc).strip().replace("|", "\\|")
    if len(d) <= n:
        return d
    cut = d[:n].rsplit(" ", 1)[0].rstrip(",;:-")
    return cut + "..."


def skill_description(fm, body):
    return fm_value(fm, "description") or first_paragraph(body) or "(no description)"


def render_index(root, warn=lambda m: None):
    overlay = read_json(os.path.join(root, "scripts", "skill-route", "overlay.json"), {})
    if not overlay:
        warn("WARN: scripts/skill-route/overlay.json missing or unreadable: every skill is listed as unrouted")
    domains, o_skills = overlay.get("domains") or {}, overlay.get("skills") or {}
    skills = list_skills(root)
    on_disk = set(n for n, _ in skills)
    for name in sorted(n for n in o_skills if n not in on_disk):
        warn("WARN: overlay.json skill not on disk: %s" % name)
    by_dom, excluded, unrouted = {}, [], []
    for name, p in skills:
        _, fm, body = load_skill(p)
        row = (name, skill_description(fm, body))
        ov = o_skills.get(name)
        if not isinstance(ov, dict):
            unrouted.append(row)
        elif ov.get("exclude"):
            excluded.append((name, "%s: %s" % (ov["exclude"], short(ov.get("why", ""), 120))))
        elif ov.get("domain") in domains:
            by_dom.setdefault(ov["domain"], []).append(row)
        else:
            unrouted.append(row)

    def table(head, rows):
        return (["| Skill | %s |" % head, "|-------|%s|" % ("-" * (len(head) + 2))]
                + ["| `%s` | %s |" % (n, short(d)) for n, d in rows] + [""])

    header = (read_text(os.path.join(root, "scripts", "skill-registry", "header.md")) or "# Skills Index\n").rstrip("\n")
    footer = (read_text(os.path.join(root, "scripts", "skill-registry", "footer.md")) or "").rstrip("\n")
    out = [header, "", GENERATED_NOTE, ""]
    for dom, desc in domains.items():
        if dom in by_dom:
            out += ["## " + dom, "", short(desc, 220), ""] + table("Description", by_dom[dom])
    if excluded:
        out += ["## Internal skills (hidden from the router menu)", "",
                "Loaded by hand or by another skill; still invokable by name.", ""]
        out += table("Why", excluded)
    if unrouted:
        out += ["## Unrouted (no router domain)", ""] + table("Description", unrouted)
    text = "\n".join(out)
    if footer:
        text += "\n" + footer + "\n"
    return text if text.endswith("\n") else text + "\n"


def registry_main(root, check):
    path = os.path.join(skills_dir(root), "INDEX.md")
    new = render_index(root, warn=lambda m: print(m, file=sys.stderr))
    cur = read_text(path)
    if cur == new:
        print("skill-registry: skills/INDEX.md is current (%d skills)" % len(list_skills(root)))
        return 0
    if check:
        print("skill-registry: skills/INDEX.md is stale. Regenerate it: python3 scripts/skill-registry.py "
              "(then commit skills/INDEX.md).")
        return 1
    os.makedirs(skills_dir(root), exist_ok=True)
    write_text(path, new)
    print("skill-registry: wrote skills/INDEX.md (%d skills)" % len(list_skills(root)))
    return 0


# ---------------------------------------------------------------------------------------------- lint
def lint_refs_two_deep(p):
    """Files under references/ that link/point to ANOTHER references/ file -> ['a.md -> b.md', ...]."""
    base, hits = os.path.join(p, "references"), []
    for dp, _, fs in os.walk(base, followlinks=True):
        for fn in sorted(fs):
            if not fn.lower().endswith(REF_TEXT):
                continue
            f = os.path.join(dp, fn)
            txt = read_text(f) or ""
            targets = {os.path.normpath(os.path.join(dp, m)) for m in MD_LINK.findall(txt) if "://" not in m}
            targets |= {os.path.normpath(os.path.join(p, m.rstrip(".,;:)`'\""))) for m in REF_MENTION.findall(txt)}
            for t in sorted(targets):
                if t != os.path.normpath(f) and t.startswith(base + os.sep) and os.path.isfile(t):
                    hits.append("%s -> %s" % (os.path.relpath(f, base).replace(os.sep, "/"),
                                              os.path.relpath(t, base).replace(os.sep, "/")))
    return hits


def lint_skill(d, p):
    """-> {rule: detail} for one skill dir."""
    text, fm, body = load_skill(p)
    out = {}
    tokens, lines = len(body) // 4, len(body.splitlines())
    if tokens > 5000:
        out["body-tokens>5000"] = "%d tokens" % tokens
    if lines > 500:
        out["body-lines>500"] = "%d lines" % lines
    dchars = len(fm_value(fm, "description")) + len(fm_value(fm, "when_to_use"))
    if dchars > 400:
        out["description>400"] = "%d chars" % dchars
    refs = lint_refs_two_deep(p)
    if refs:
        out["refs-two-deep"] = "; ".join(refs[:3]) + (" (+%d more)" % (len(refs) - 3) if len(refs) > 3 else "")
    hp = re.findall(r"(?:~|\$\{?HOME\}?|/[Uu]sers/[^/\s]+|/home/[^/\s]+)/\.claude/skills/%s/" % re.escape(d), text)
    if hp:
        out["hardcoded-self-path"] = "%d use(s) of a machine path to skills/%s/" % (len(hp), d)
    for k in fm_keys(fm):
        if k not in SPEC:
            out["non-spec-key:" + k] = "top-level frontmatter key '%s' is not in the spec set" % k
    return out


def lint_main(root, baseline_path, changed, update_baseline):
    skills = list_skills(root)
    names = set(n for n, _ in skills)
    scope = None  # None = every skill
    if changed:
        scope = set()
        base = skills_dir(root)
        for c in changed:
            rel = os.path.relpath(os.path.abspath(os.path.expanduser(c)), base)
            top = rel.replace(os.sep, "/").split("/")[0]
            if rel.startswith("..") or top not in names:
                print("WARN: --changed-only path is not inside a skill dir under %s: %s" % (base, c), file=sys.stderr)
            else:
                scope.add(top)
    todo = [(n, p) for n, p in skills if scope is None or n in scope]
    found = {}  # "<skill>:<rule>" -> detail
    for d, p in todo:
        for rule, detail in lint_skill(d, p).items():
            found["%s:%s" % (d, rule)] = detail
    base_v = read_json(baseline_path, {}).get("violations", {})
    in_scope = lambda key: scope is None or key.split(":", 1)[0] in scope
    if update_baseline:
        kept = {k: v for k, v in base_v.items() if not in_scope(k)}
        merged = dict(kept)
        merged.update(found)
        data = {"version": 1,
                "note": "Ratchet baseline for `python3 scripts/skill-registry.py --lint`: violations that exist today; "
                        "only NEW keys fail. Shrink it, never grow it by hand.",
                "violations": dict(sorted(merged.items()))}
        os.makedirs(os.path.dirname(baseline_path), exist_ok=True)
        write_text(baseline_path, json.dumps(data, indent=2, ensure_ascii=False) + "\n")
        print("lint: baseline written (%d entries; %d from %d checked skill(s)) -> %s"
              % (len(data["violations"]), len(found), len(todo), baseline_path))
        return 0
    new = sorted(k for k in found if k not in base_v)
    for k in new:
        skill, rule = k.split(":", 1)
        print("LINT FAIL %s %s: %s" % (skill, rule, found[k]))
    fixed = sorted(k for k in base_v if in_scope(k) and k not in found)
    for k in fixed:
        print("LINT FIXED (remove with --update-baseline): %s" % k)
    print("lint: %d skill(s) checked%s, %d violation(s), %d baselined, %d NEW, %d baseline entr%s now fixed -> %s" % (
        len(todo), " (--changed-only)" if scope is not None else "", len(found), len(found) - len(new), len(new),
        len(fixed), "y" if len(fixed) == 1 else "ies", "FAIL" if new else "OK"))
    return 1 if new else 0


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate skills/INDEX.md and lint the skills (see the module docstring).")
    ap.add_argument("--root", default=default_root(), help="agency root (default: the directory above scripts/)")
    ap.add_argument("--check", action="store_true", help="exit 1 if skills/INDEX.md is stale; write nothing")
    ap.add_argument("--lint", action="store_true", help="ratcheting skill lint; exit 1 on NEW violations")
    ap.add_argument("--changed-only", nargs="+", metavar="PATH", help="with --lint: only the skill dirs containing these paths")
    ap.add_argument("--update-baseline", action="store_true", help="with --lint: rewrite the baseline from today's violations")
    ap.add_argument("--baseline", help="lint baseline file (default: <root>/scripts/skill-registry/lint-baseline.json)")
    a = ap.parse_args(argv)
    root = os.path.abspath(a.root)
    if a.lint:
        baseline = a.baseline or os.path.join(root, "scripts", "skill-registry", "lint-baseline.json")
        return lint_main(root, baseline, a.changed_only, a.update_baseline)
    return registry_main(root, a.check)


if __name__ == "__main__":
    sys.exit(main())
